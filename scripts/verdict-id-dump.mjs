// g4: collect every /dispute and /v/:tx response type over real HTTP, for an independent (python) recomputation of verdict_id from the response alone.
// Usage: node scripts/verdict-id-dump.mjs OUT.json   then   python3 -I scripts/verdict-id-recompute.py OUT.json   (the independent check; test/phase18/n9-verdict-id-independent.test.js runs both)
import http from 'node:http';
import fs from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { mandateId } from '@iussum/core';
import { createResolverApp, openStore } from '@iussum/resolver';
import { T0, SRC, mandate, receipt } from '../test/fixtures.mjs';
import { chainSim, grantAt, payAt, live, sig } from '../test/regression/chainsim.mjs';
import { service } from '../test/phase12/helpers.mjs';
const M = mandate({ nonce: '4e'.repeat(16) });
const G = sig('G'); const P = [1, 2, 3, 4, 5].map((i) => sig(`P${i}`));
const chain = () => { const c = chainSim(); c.add('G', grantAt(M, 1000)); P.forEach((p, i) => c.add(`P${i + 1}`, payAt(1100 + 100 * i))); c.setAccount(SRC, live(M)); return c; };
const rc = (i, ro = {}) => receipt({ mandate_id: mandateId(M), grant_tx: G, tx_sig: P[i], amount: '10000', settled_at: T0 + 1100 + 100 * i, ...ro });
const BAD = 'https://not-allowed.example/x';
const file = `${process.env.TMPDIR ?? '/tmp'}/g4-${process.pid}.sqlite`;
let store = openStore(file); let { svc } = service(chain(), { store });
const out = [];
async function serve(s) { const srv = http.createServer(createResolverApp(s)); await new Promise((ok) => srv.listen(0, '127.0.0.1', ok)); return { srv, base: `http://127.0.0.1:${srv.address().port}` }; }
let web = await serve(svc);
const post = async (name, b) => { const r = await fetch(`${web.base}/dispute`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(b) }); const body = await r.json(); out.push({ name, kind: 'dispute', status: r.status, body, sent_receipt: b.receipt ?? null }); return body; };
const page = async (name, tx) => { const t = await (await fetch(`${web.base}/v/${tx}`)).text(); out.push({ name, kind: 'page', text: t }); };
const B = (i, r, o = {}) => ({ tx_sig: P[i], mandate: M, grant_tx: G, receipt: r, ...o });
await post('fresh out-of-scope final', B(0, rc(0, { resource: BAD })));
await post('duplicate of it', B(0, rc(0, { resource: BAD })));
await post('duplicate without receipt, grant_tx null', B(0, null, { grant_tx: null }));
await page('page fresh', P[0]);
await post('fresh in_scope final', B(1, rc(1)));
await post('provisional (no receipt)', B(2, null));
await post('duplicate of provisional, no receipt', B(2, null));
await post('provisional replaced by receipt', B(2, rc(2, { resource: BAD })));
await page('page replaced', P[2]);
await post('equivocation on in_scope final', B(1, rc(1, { resource: BAD })));
await post('duplicate after equivocation', B(1, rc(1, { resource: 'https://not-allowed.example/y' })));
await page('page equivocation', P[1]);
await post('provisional to become legacy', B(3, null));
await post('final to become legacy', B(4, rc(4, { resource: BAD })));
web.srv.close(); store.close();
const db = new DatabaseSync(file); db.prepare('UPDATE verdicts SET verdict_id = NULL, grant_tx = NULL WHERE tx_sig IN (?, ?)').run(P[3], P[4]); db.close();
store = openStore(file); ({ svc } = service(chain(), { store })); web = await serve(svc);
await post('legacy final duplicate', B(4, rc(4, { resource: BAD })));
await page('page legacy final', P[4]);
await post('legacy provisional replaced', B(3, rc(3, { resource: BAD })));
await page('page legacy provisional replaced', P[3]);
await post('equivocation on legacy final', B(4, rc(4, { resource: 'https://not-allowed.example/z' })));
web.srv.close(); store.close();
fs.writeFileSync(process.argv[2], JSON.stringify(out, null, 1));
console.log(`${out.length} responses written`);
process.exit(0);
